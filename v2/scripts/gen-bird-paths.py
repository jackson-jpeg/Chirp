#!/usr/bin/env python3
"""Generate v2/App/Sources/Design/BirdPaths.swift from the approved design.

Reads the `bird`, `beakClosed` and `beakOpen` symbols out of
v2/design/source/Main.dc.html and writes each SVG path as SwiftUI Path code,
so the app draws exactly the approved drawing. Run it again if the design's
bird ever changes:

    python3 -I v2/scripts/gen-bird-paths.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "design/source/Main.dc.html"
OUT = ROOT / "App/Sources/Design/BirdPaths.swift"

html = SRC.read_text()


def symbol(name):
    m = re.search(rf'<symbol id="{name}"[^>]*>(.*?)</symbol>', html, re.S)
    if not m:
        sys.exit(f"symbol {name} not found in {SRC}")
    return m.group(1)


def swift_path(d):
    toks = re.findall(r"[MCLQZmclqz]|-?\d*\.?\d+", d)
    out, i, cmd = [], 0, None
    def num():
        nonlocal i
        v = toks[i]; i += 1
        return v
    while i < len(toks):
        if re.match(r"[A-Za-z]", toks[i]):
            cmd = toks[i]; i += 1
            if cmd.islower():
                sys.exit(f"relative command {cmd} not supported")
        if cmd == "M":
            x, y = num(), num(); out.append(f"p.move(to: .init(x: {x}, y: {y}))")
            cmd = "L"
        elif cmd == "L":
            x, y = num(), num(); out.append(f"p.addLine(to: .init(x: {x}, y: {y}))")
        elif cmd == "C":
            a = [num() for _ in range(6)]
            out.append(f"p.addCurve(to: .init(x: {a[4]}, y: {a[5]}), control1: .init(x: {a[0]}, y: {a[1]}), control2: .init(x: {a[2]}, y: {a[3]}))")
        elif cmd == "Q":
            a = [num() for _ in range(4)]
            out.append(f"p.addQuadCurve(to: .init(x: {a[2]}, y: {a[3]}), control: .init(x: {a[0]}, y: {a[1]}))")
        elif cmd == "Z":
            out.append("p.closeSubpath()")
            cmd = None
        else:
            sys.exit(f"unexpected token {toks[i]!r}")
    return "Path { p in\n            " + "\n            ".join(out) + "\n        }"


def paths(sym):
    return re.findall(r'<path d="([^"]+)"', sym)


bird = paths(symbol("bird"))
closed = paths(symbol("beakClosed"))
opened = paths(symbol("beakOpen"))
# Order in the symbol: tail, body, tuft, belly, cap, wing, wing lines, legs, feet.
names = ["tail", "body", "tuft", "belly", "cap", "wing", "wingLines", "legs", "feet"]
if len(bird) != len(names):
    sys.exit(f"expected {len(names)} paths in bird, found {len(bird)}")

lines = [
    "// GENERATED by v2/scripts/gen-bird-paths.py from v2/design/source/Main.dc.html.",
    "// Do not edit by hand: change the design, then run the script again.",
    "import SwiftUI",
    "",
    "/// The approved Dawn Chorus bird, in the design's own coordinates: the",
    "/// `bird` symbol is centred on (0, 0) (viewBox -180 -120 340 260, drawn with",
    "/// overflow), and a beak sits at (112, -52) in the same space.",
    "enum BirdPaths {",
]
for n, d in zip(names, bird):
    lines.append(f"    static let {n} = {swift_path(d)}")
for n, d in zip(["beakClosedUpper", "beakClosedLine"], closed):
    lines.append(f"    static let {n} = {swift_path(d)}")
for n, d in zip(["beakOpenUpper", "beakOpenLower", "beakOpenMouth"], opened):
    lines.append(f"    static let {n} = {swift_path(d)}")
lines.append("}")
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT}")
